import PDFDocument from "pdfkit";

const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "A4",
        margin: 50,
        info: {
          Author: "Solvix",
          Title: data?.title || "Solvix Document",
          Creator: "Solvix",
        },
      });

      const chunks = [];

      doc.on("data", (chunk) => {
        chunks.push(chunk);
      });

      doc.on("end", () => {
        const buffer = Buffer.concat(chunks);
        console.log(`✅ PDF buffer created: ${buffer.length} bytes`);
        resolve(buffer);
      });

      doc.on("error", (error) => {
        reject(error);
      });

      // TITLE
      doc
        .fillColor("#111827")
        .fontSize(24)
        .font("Helvetica-Bold")
        .text(data?.title || "Solvix Document", {
          align: "center",
        });

      // SUBTITLE
      if (data?.subtitle) {
        doc.moveDown(0.5);
        doc
          .fillColor("#4B5563")
          .fontSize(12)
          .font("Helvetica")
          .text(data.subtitle, {
            align: "center",
          });
      }

      doc.moveDown(2);

      // SECTIONS
      const sections = Array.isArray(data?.sections) ? data.sections : [];

      sections.forEach((section) => {
        if (section?.heading) {
          doc
            .fillColor("#111827")
            .fontSize(18)
            .font("Helvetica-Bold")
            .text(section.heading);
          doc.moveDown(0.5);
        }

        const points = Array.isArray(section?.points) ? section.points : [];

        points.forEach((point) => {
          if (!point) return;
          doc
            .fillColor("#374151")
            .fontSize(12)
            .font("Helvetica")
            .text(`• ${point}`, {
              lineGap: 5,
              indent: 10,
            });
          doc.moveDown(0.3);
        });

        doc.moveDown(0.8);
      });

      // FOOTER
      doc
        .fillColor("#6B7280")
        .fontSize(10)
        .font("Helvetica")
        .text("Generated By Solvix • Siraj Abid", {
          align: "center",
        });

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
};

export default generatePdf;