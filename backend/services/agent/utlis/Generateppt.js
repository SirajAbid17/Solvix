// backend/services/agent/utlis/Generateppt.js
import pptxgen from "pptxgenjs";

export const Generateppt = async (data, outputPath = "./presentation.pptx") => {
  try {
    // ============================================
    // COLORS
    // ============================================

    const colors = {
      primary: "2563EB",
      primaryDark: "1D4ED8",
      secondary: "0F172A",
      text: "334155",
      light: "F8FAFC",
      lighter: "EFF6FF",
      border: "E2E8F0",
      white: "FFFFFF",
      muted: "64748B",
      accent: "60A5FA",
      subtitle: "DBEAFE",
      chart1: "2563EB",
      chart2: "60A5FA",
      chart3: "93C5FD",
      chart4: "BFDBFE",
      chart5: "1D4ED8",
    };

    // ============================================
    // CREATE PRESENTATION
    // ============================================

    const ppt = new pptxgen();

    ppt.layout = "LAYOUT_WIDE";

    ppt.author = "SOLVIX_AI";
    ppt.company = "Solvix_AI";
    ppt.subject = data?.title || "Presentation";
    ppt.title = data?.title || "Presentation";
    ppt.lang = "en_US";

    ppt.theme = {
      headFontFace: "Aptos",
      bodyFontFace: "Aptos",
      lang: "en_US",
    };

    // ============================================
    // COVER SLIDE
    // ============================================

    const addCover = (ppt, data) => {
      const slide = ppt.addSlide();

      slide.background = { color: colors.primary };

      slide.addShape(ppt.ShapeType.rect, {
        x: 0, y: 0, w: 13.33, h: 0.18,
        fill: { color: colors.accent },
        line: { color: colors.accent },
      });

      slide.addText(data?.title || "Presentation", {
        x: 0.7, y: 1.7, w: 12, h: 0.9,
        align: "center", valign: "mid",
        color: colors.white, bold: true,
        fontFace: "Aptos Display", fontSize: 28,
        margin: 0, fit: "shrink",
      });

      slide.addText(data?.subtitle || "", {
        x: 1, y: 2.8, w: 11.5, h: 0.5,
        align: "center", valign: "mid",
        color: colors.subtitle, bold: true,
        fontFace: "Aptos", fontSize: 15,
        margin: 0, fit: "shrink",
      });

      slide.addShape(ppt.ShapeType.line, {
        x: 4.2, y: 3.55, w: 4.9, h: 0,
        line: { color: colors.accent, width: 2 },
      });

      slide.addText("Generated by SolvixAI", {
        x: 0, y: 6.9, w: 13.33, h: 0.2,
        align: "center", color: colors.subtitle,
        bold: true, fontFace: "Aptos", fontSize: 10,
        margin: 0,
      });
    };

    // ============================================
    // CONTENT SLIDE
    // ============================================

    const addContentSlide = (ppt, slideData, page, total) => {
      const slide = ppt.addSlide();

      slide.background = { color: colors.white };

      slide.addText(slideData?.title || "Untitled Slide", {
        x: 0.6, y: 0.35, w: 10.8, h: 0.5,
        align: "left", valign: "mid",
        color: colors.primary, bold: true,
        fontFace: "Aptos Display", fontSize: 24,
        margin: 0, fit: "shrink",
      });

      slide.addShape(ppt.ShapeType.line, {
        x: 0.6, y: 0.95, w: 12, h: 0,
        line: { color: colors.border, width: 1.2 },
      });

      let yPosition = 1.2;

      if (slideData?.paragraph || slideData?.content) {
        const paragraph = slideData.paragraph || slideData.content;
        const paragraphs = paragraph.split("\n").filter((p) => p.trim());

        paragraphs.forEach((para, idx) => {
          const trimmed = para.trim();
          if (
            trimmed.startsWith("•") ||
            trimmed.startsWith("-") ||
            trimmed.startsWith("*")
          ) return;

          slide.addShape(ppt.ShapeType.roundRect, {
            x: 0.7, y: yPosition, w: 11.95, h: 0.7,
            rectRadius: 0.08,
            fill: { color: idx % 2 === 0 ? colors.lighter : colors.light },
            line: { color: colors.border, width: 0.5 },
          });

          slide.addText(trimmed, {
            x: 1.0, y: yPosition + 0.05, w: 11.3, h: 0.6,
            align: "left", valign: "mid",
            color: colors.text, fontFace: "Aptos",
            fontSize: 13, margin: 0, fit: "shrink",
          });

          yPosition += 0.85;
        });

        yPosition += 0.3;
      }

      const points = Array.isArray(slideData?.points)
        ? slideData.points.slice(0, 6)
        : [];

      points.forEach((point, index) => {
        const y = yPosition + index * 0.75;

        slide.addShape(ppt.ShapeType.roundRect, {
          x: 0.7, y, w: 11.95, h: 0.6,
          rectRadius: 0.08,
          fill: { color: index % 2 === 0 ? colors.lighter : colors.light },
          line: { color: colors.border, width: 0.5 },
        });

        slide.addShape(ppt.ShapeType.ellipse, {
          x: 0.92, y: y + 0.2, w: 0.12, h: 0.12,
          fill: { color: colors.primary },
          line: { color: colors.primary, width: 0.5 },
        });

        slide.addText(String(point || ""), {
          x: 1.2, y: y + 0.05, w: 11, h: 0.5,
          align: "left", valign: "mid",
          color: colors.text, fontFace: "Aptos",
          fontSize: 14, margin: 0, fit: "shrink",
        });
      });

      slide.addText("Solvix", {
        x: 0.6, y: 6.9, w: 2, h: 0.2,
        align: "left", color: colors.muted,
        bold: true, fontFace: "Aptos", fontSize: 10,
        margin: 0,
      });

      slide.addText(`${page}/${total}`, {
        x: 11.8, y: 6.9, w: 0.85, h: 0.2,
        align: "right", color: colors.muted,
        bold: true, fontFace: "Aptos", fontSize: 10,
        margin: 0,
      });
    };

    // ============================================
    // BUILD 25 LINES (5 x 5)
    // ============================================

    const buildSummaryLines = (data) => {
      const title = data?.title || "this topic";
      const subtitle = data?.subtitle || "";

      const allPoints = (data?.slides || [])
        .flatMap((s) => (Array.isArray(s?.points) ? s.points : []))
        .filter(Boolean);

      const totalPoints = allPoints.length;
      const totalSlides = (data?.slides || []).length;

      const lines = [
        `${title} is a comprehensive, multi-dimensional subject carefully structured across ${totalSlides} thematic sections in this presentation.`,
        `The presentation establishes a strong foundation, introducing the core concepts, background, and essential context needed for deep understanding.`,
        subtitle
          ? `The central theme "${subtitle}" anchors the entire discussion and provides the reader with a clear and focused direction throughout.`
          : `The central theme anchors the entire discussion and provides the reader with a clear and focused direction throughout.`,
        `Each section has been thoughtfully designed to build upon the previous one, ensuring a smooth, logical, and easy-to-follow flow of ideas.`,
        `The structure is intentionally modular so that every key area receives adequate attention while still contributing to a unified narrative.`,
        `Together, these sections cover approximately ${totalPoints} key bullet points highlighting the most important insights and takeaways.`,
        `From a strategic perspective, ${title} plays a significant role in shaping outcomes, influencing decisions, and driving measurable value.`,
        `It combines theoretical understanding with practical application, making it relevant both for new learners and experienced professionals.`,
        `One of the most important observations is that ${title} cannot be viewed in isolation from other internal or external factors.`,
        `It interacts with technology, human behavior, market dynamics, and organizational priorities in complex and often unpredictable ways.`,
        `Understanding these interactions is essential for making informed decisions and for anticipating future trends with confidence.`,
        `The presentation also highlights several emerging developments and opportunities that are likely to shape the future of ${title}.`,
        `These developments suggest that continuous learning, adaptability, and innovation will remain critical success factors in the coming years.`,
        `In terms of benefits, ${title} offers improved efficiency, better decision-making, enhanced clarity, and stronger strategic alignment.`,
        `At the same time, it introduces certain challenges — such as complexity, resource requirements, and the need for skilled implementation.`,
        `Addressing these challenges proactively can unlock substantial long-term value and create a sustainable competitive advantage.`,
        `The visual chart included in these summary slides summarizes the relative emphasis placed on each major section of the presentation.`,
        `It provides a quick, at-a-glance understanding of how the content is distributed and where the strongest focus lies.`,
        `Overall, ${title} is a topic of lasting importance, and the insights presented here serve as a practical reference for further exploration.`,
        `The presentation concludes with a clear set of takeaways that can be directly applied, adapted, and expanded upon in future work.`,
        `In summary, this presentation delivers a complete, structured, and insightful overview of ${title} with clarity, depth, and relevance.`,
        `It supports both understanding and action, making it a valuable resource for students, professionals, and decision-makers alike.`,
        `The ideas presented can be extended into workshops, strategy sessions, or further research depending on the reader's specific goals.`,
        `Finally, the content has been kept concise, visually consistent, and easy to navigate so that the key message is never lost.`,
        `We hope this presentation provides a strong starting point for deeper discussion and meaningful real-world application.`,
      ];

      // Guarantee at least 25 lines
      while (lines.length < 25) {
        lines.push(
          `Further analysis of ${title} continues to reveal new perspectives and reinforces the importance of ongoing study and reflection.`
        );
      }

      return lines.slice(0, 25);
    };

    // ============================================
    // HELPER: BAR CHART
    // ============================================

    const addEmphasisChart = (ppt, slide, data, x, y, w, h) => {
      const chartLabels = (data?.slides || []).map((s, i) => {
        const t = s?.title || `Section ${i + 1}`;
        return t.length > 12 ? t.slice(0, 10) + "…" : t;
      });

      const chartValues = (data?.slides || []).map((s) =>
        Array.isArray(s?.points) ? s.points.length : 0
      );

      const chartColors = [
        colors.chart1, colors.chart2, colors.chart3,
        colors.chart4, colors.chart5, colors.chart1,
      ];

      const chartData = [
        { name: "Points", labels: chartLabels, values: chartValues },
      ];

      slide.addChart(ppt.ChartType.bar, chartData, {
        x, y, w, h,
        barDir: "col",
        chartColors,
        showLegend: false,
        showTitle: false,
        showValue: true,
        dataLabelColor: colors.text,
        dataLabelFontSize: 10,
        catAxisLabelColor: colors.text,
        catAxisLabelFontSize: 9,
        valAxisLabelColor: colors.muted,
        valAxisLabelFontSize: 9,
        valGridLine: { color: colors.border, style: "dash", size: 0.5 },
        catGridLine: { style: "none" },
        barGapWidthPct: 55,
        border: { pt: 0, color: colors.white },
      });
    };

    // ============================================
    // SUMMARY SLIDE (5 lines + chart)
    // ============================================

    const addSummarySlide = (ppt, data, lines, partNumber, totalParts, chartTitle) => {
      const slide = ppt.addSlide();
      slide.background = { color: colors.white };

      slide.addText(`Detailed Summary — Part ${partNumber}`, {
        x: 0.5, y: 0.25, w: 10, h: 0.45,
        align: "left", valign: "mid",
        color: colors.primary, bold: true,
        fontFace: "Aptos Display", fontSize: 20,
        margin: 0,
      });

      slide.addShape(ppt.ShapeType.line, {
        x: 0.5, y: 0.78, w: 12.3, h: 0,
        line: { color: colors.border, width: 1 },
      });

      // ---- LEFT: 5 lines paragraph ----
      slide.addShape(ppt.ShapeType.roundRect, {
        x: 0.5, y: 1.1, w: 7.3, h: 5.3,
        rectRadius: 0.08,
        fill: { color: colors.lighter },
        line: { color: colors.border, width: 0.5 },
      });

      const text = lines.join("\n\n");

      slide.addText(text, {
        x: 0.75, y: 1.3, w: 6.85, h: 4.95,
        align: "left", valign: "top",
        color: colors.text, fontFace: "Aptos",
        fontSize: 14, margin: 0,
        lineSpacingMultiple: 1.4,
        fit: "shrink",
      });

      // ---- RIGHT: chart ----
      slide.addShape(ppt.ShapeType.roundRect, {
        x: 8.0, y: 1.1, w: 4.8, h: 5.3,
        rectRadius: 0.08,
        fill: { color: colors.white },
        line: { color: colors.border, width: 0.5 },
      });

      slide.addText(chartTitle, {
        x: 8.2, y: 1.25, w: 4.4, h: 0.4,
        align: "left", valign: "mid",
        color: colors.primary, bold: true,
        fontFace: "Aptos", fontSize: 14,
        margin: 0,
      });

      addEmphasisChart(ppt, slide, data, 8.2, 1.75, 4.4, 4.5);

      // ---- Footer ----
      slide.addText("Solvix", {
        x: 0.5, y: 6.9, w: 2, h: 0.2,
        align: "left", color: colors.muted,
        bold: true, fontFace: "Aptos", fontSize: 10,
        margin: 0,
      });

      slide.addText(`Summary ${partNumber}/${totalParts}`, {
        x: 11.0, y: 6.9, w: 1.8, h: 0.2,
        align: "right", color: colors.muted,
        bold: true, fontFace: "Aptos", fontSize: 10,
        margin: 0,
      });
    };

    // ============================================
    // THANK YOU SLIDE
    // ============================================

    const addThankyou = (ppt) => {
      const slide = ppt.addSlide();

      slide.background = { color: colors.secondary };

      slide.addShape(ppt.ShapeType.rect, {
        x: 0, y: 0, w: 13.33, h: 0.18,
        fill: { color: colors.accent },
        line: { color: colors.accent },
      });

      slide.addText("Thank You", {
        x: 1, y: 2.4, w: 11.3, h: 0.8,
        align: "center", valign: "mid",
        color: colors.white, bold: true,
        fontFace: "Aptos Display", fontSize: 34,
        margin: 0,
      });

      slide.addText("Generated by SolvixAI", {
        x: 1, y: 3.45, w: 11.3, h: 0.4,
        align: "center", color: colors.subtitle,
        fontFace: "Aptos", fontSize: 14,
        margin: 0,
      });

      slide.addText("SOLVIX_AI", {
        x: 0, y: 6.9, w: 13.33, h: 0.2,
        align: "center", color: colors.muted,
        bold: true, fontFace: "Aptos", fontSize: 10,
        margin: 0,
      });
    };

    // ============================================
    // VALIDATE DATA
    // ============================================

    if (!data) throw new Error("Presentation data is required.");
    if (!Array.isArray(data.slides))
      throw new Error("Presentation slides must be an array.");

    // ============================================
    // GENERATE SLIDES
    // ============================================

    // 1) Cover
    addCover(ppt, data);

    // 2) Content slides
    data.slides.forEach((slideData, index) => {
      addContentSlide(ppt, slideData, index + 1, data.slides.length);
    });

    // 3) ✅ Build 25 lines, split into 5 chunks of 5
    const summaryLines = buildSummaryLines(data);
    const chunks = [];
    for (let i = 0; i < 25; i += 5) {
      chunks.push(summaryLines.slice(i, i + 5));
    }

    // 4) ✅ Create 5 summary slides (5 lines each)
    const chartTitles = [
      "Section Emphasis",
      "Key Insights",
      "Strategic Focus",
      "Impact Areas",
      "Final Takeaways",
    ];

    chunks.forEach((chunk, idx) => {
      addSummarySlide(
        ppt,
        data,
        chunk,
        idx + 1,
        chunks.length,
        chartTitles[idx] || `Summary ${idx + 1}`
      );
    });

    // 5) Thank You
    addThankyou(ppt);

    // ============================================
    // SAVE FILE
    // ============================================

    await ppt.writeFile({ fileName: outputPath });

    console.log(`PPT generated successfully: ${outputPath}`);

    return ppt;
  } catch (error) {
    console.error("PPT GENERATION ERROR:", error);
    throw error;
  }
};