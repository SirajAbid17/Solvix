import pptxgen from "pptxgenjs";

export const Generateppt = async (data, outputPath = "./presentation.pptx") => {
  try {
    // ============================================
    // COLORS
    // ============================================

    const colors = {
      primary: "2563EB",
      primaryDark: "1D4ED8",
      secondary: "0F172A",
      text: "334155",
      light: "F8FAFC",
      lighter: "EFF6FF",
      border: "E2E8F0",
      white: "FFFFFF",
      muted: "64748B",
      accent: "60A5FA",
      subtitle: "DBEAFE",
    };

    // ============================================
    // CREATE PRESENTATION
    // ============================================

    const ppt = new pptxgen();

    ppt.layout = "LAYOUT_WIDE";

    ppt.author = "SOLVIX_AI";
    ppt.company = "Solvix_AI";
    ppt.subject = data?.title || "Presentation";
    ppt.title = data?.title || "Presentation";
    ppt.lang = "en_US";

    ppt.theme = {
      headFontFace: "Aptos",
      bodyFontFace: "Aptos",
      lang: "en_US",
    };

    // ============================================
    // COVER SLIDE
    // ============================================

    const addCover = (ppt, data) => {
      const slide = ppt.addSlide();

      slide.background = {
        color: colors.primary,
      };

      slide.addShape(ppt.ShapeType.rect, {
        x: 0,
        y: 0,
        w: 13.33,
        h: 0.18,
        fill: { color: colors.accent },
        line: { color: colors.accent },
      });

      slide.addText(data?.title || "Presentation", {
        x: 0.7,
        y: 1.7,
        w: 12,
        h: 0.9,
        align: "center",
        valign: "mid",
        color: colors.white,
        bold: true,
        fontFace: "Aptos Display",
        fontSize: 28,
        breakLine: false,
        margin: 0,
        fit: "shrink",
      });

      slide.addText(data?.subtitle || "", {
        x: 1,
        y: 2.8,
        w: 11.5,
        h: 0.5,
        align: "center",
        valign: "mid",
        color: colors.subtitle,
        bold: true,
        fontFace: "Aptos",
        fontSize: 15,
        margin: 0,
        fit: "shrink",
      });

      slide.addShape(ppt.ShapeType.line, {
        x: 4.2,
        y: 3.55,
        w: 4.9,
        h: 0,
        line: { color: colors.accent, width: 2 },
      });

      slide.addText("Generated by SolvixAI", {
        x: 0,
        y: 6.9,
        w: 13.33,
        h: 0.2,
        align: "center",
        color: colors.subtitle,
        bold: true,
        fontFace: "Aptos",
        fontSize: 10,
        margin: 0,
      });
    };

    // ============================================
    // CONTENT SLIDE - With Paragraph Support
    // ============================================

    const addContentSlide = (ppt, slideData, page, total) => {
      const slide = ppt.addSlide();

      slide.background = {
        color: colors.white,
      };

      // ==========================================
      // SLIDE TITLE
      // ==========================================

      slide.addText(slideData?.title || "Untitled Slide", {
        x: 0.6,
        y: 0.35,
        w: 10.8,
        h: 0.5,
        align: "left",
        valign: "mid",
        color: colors.primary,
        bold: true,
        fontFace: "Aptos Display",
        fontSize: 24,
        margin: 0,
        fit: "shrink",
      });

      // ==========================================
      // TITLE UNDERLINE
      // ==========================================

      slide.addShape(ppt.ShapeType.line, {
        x: 0.6,
        y: 0.95,
        w: 12,
        h: 0,
        line: { color: colors.border, width: 1.2 },
      });

      // ==========================================
      // PARAGRAPH CONTENT (if exists)
      // ==========================================

      let yPosition = 1.2;

      // ✅ If there's paragraph content, display it first
      if (slideData?.paragraph || slideData?.content) {
        const paragraph = slideData.paragraph || slideData.content;
        
        // Split into paragraphs
        const paragraphs = paragraph.split('\n').filter(p => p.trim());
        
        paragraphs.forEach((para, idx) => {
          // Check if it's a heading or bullet point style
          const trimmed = para.trim();
          
          if (trimmed.startsWith('•') || trimmed.startsWith('-') || trimmed.startsWith('*')) {
            // It's a bullet point - handled separately
            return;
          }
          
          // It's a paragraph
          slide.addShape(ppt.ShapeType.roundRect, {
            x: 0.7,
            y: yPosition,
            w: 11.95,
            h: 0.7,
            rectRadius: 0.08,
            fill: { color: idx % 2 === 0 ? colors.lighter : colors.light },
            line: { color: colors.border, width: 0.5 },
          });

          slide.addText(trimmed, {
            x: 1.0,
            y: yPosition + 0.05,
            w: 11.3,
            h: 0.6,
            align: "left",
            valign: "mid",
            color: colors.text,
            fontFace: "Aptos",
            fontSize: 13,
            margin: 0,
            fit: "shrink",
          });

          yPosition += 0.85;
        });

        // Add small gap after paragraphs
        yPosition += 0.3;
      }

      // ==========================================
      // BULLET POINTS
      // ==========================================

      const points = Array.isArray(slideData?.points) ? slideData.points.slice(0, 6) : [];

      points.forEach((point, index) => {
        const y = yPosition + index * 0.75;

        // Point container
        slide.addShape(ppt.ShapeType.roundRect, {
          x: 0.7,
          y,
          w: 11.95,
          h: 0.6,
          rectRadius: 0.08,
          fill: { color: index % 2 === 0 ? colors.lighter : colors.light },
          line: { color: colors.border, width: 0.5 },
        });

        // Bullet circle
        slide.addShape(ppt.ShapeType.ellipse, {
          x: 0.92,
          y: y + 0.2,
          w: 0.12,
          h: 0.12,
          fill: { color: colors.primary },
          line: { color: colors.primary, width: 0.5 },
        });

        // Point text
        slide.addText(String(point || ""), {
          x: 1.2,
          y: y + 0.05,
          w: 11,
          h: 0.5,
          align: "left",
          valign: "mid",
          color: colors.text,
          fontFace: "Aptos",
          fontSize: 14,
          margin: 0,
          fit: "shrink",
        });
      });

      // ==========================================
      // FOOTER
      // ==========================================

      slide.addText("Solvix", {
        x: 0.6,
        y: 6.9,
        w: 2,
        h: 0.2,
        align: "left",
        color: colors.muted,
        bold: true,
        fontFace: "Aptos",
        fontSize: 10,
        margin: 0,
      });

      slide.addText(`${page}/${total}`, {
        x: 11.8,
        y: 6.9,
        w: 0.85,
        h: 0.2,
        align: "right",
        color: colors.muted,
        bold: true,
        fontFace: "Aptos",
        fontSize: 10,
        margin: 0,
      });
    };

    // ============================================
    // THANK YOU SLIDE
    // ============================================

    const addThankyou = (ppt) => {
      const slide = ppt.addSlide();

      slide.background = {
        color: colors.secondary,
      };

      slide.addShape(ppt.ShapeType.rect, {
        x: 0,
        y: 0,
        w: 13.33,
        h: 0.18,
        fill: { color: colors.accent },
        line: { color: colors.accent },
      });

      slide.addText("Thank You", {
        x: 1,
        y: 2.4,
        w: 11.3,
        h: 0.8,
        align: "center",
        valign: "mid",
        color: colors.white,
        bold: true,
        fontFace: "Aptos Display",
        fontSize: 34,
        margin: 0,
      });

      slide.addText("Generated by SolvixAI", {
        x: 1,
        y: 3.45,
        w: 11.3,
        h: 0.4,
        align: "center",
        color: colors.subtitle,
        fontFace: "Aptos",
        fontSize: 14,
        margin: 0,
      });

      slide.addText("SOLVIX_AI", {
        x: 0,
        y: 6.9,
        w: 13.33,
        h: 0.2,
        align: "center",
        color: colors.muted,
        bold: true,
        fontFace: "Aptos",
        fontSize: 10,
        margin: 0,
      });
    };

    // ============================================
    // VALIDATE DATA
    // ============================================

    if (!data) {
      throw new Error("Presentation data is required.");
    }

    if (!Array.isArray(data.slides)) {
      throw new Error("Presentation slides must be an array.");
    }

    // ============================================
    // GENERATE COVER
    // ============================================

    addCover(ppt, data);

    // ============================================
    // GENERATE CONTENT SLIDES
    // ============================================

    data.slides.forEach((slideData, index) => {
      addContentSlide(
        ppt,
        slideData,
        index + 1,
        data.slides.length,
      );
    });

    // ============================================
    // THANK YOU
    // ============================================

    addThankyou(ppt);

    // ============================================
    // SAVE FILE
    // ============================================

    await ppt.writeFile({
      fileName: outputPath,
    });

    console.log(`PPT generated successfully: ${outputPath}`);

    return ppt;
  } catch (error) {
    console.error("PPT GENERATION ERROR:", error);

    throw error;
  }
};